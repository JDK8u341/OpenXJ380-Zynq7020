#pragma once

/*
 * 上游 <cpu/lock.h> 的 **ARM 覆盖层** —— 架构覆盖层的第一个文件。
 *
 * ====================================================================
 * 为什么需要"覆盖层"
 * ====================================================================
 *
 * 上游 `include/cpu/lock.h` 是**纯 x86 内联汇编**:
 *   `pushfq` / `popfq` / `cli` / `lock btsq` / `mfence` / `pause` ……
 * 它在 ARM 上不是"编出来行为不对",而是**根本编不过**:
 *   error: impossible constraint in 'asm'
 * 而 `driver/fs/**` 里 **9 个上游文件**都直接或间接包含它
 * (vfs.cpp / tmpfs.cpp / dev.cpp / pty.cpp / socketfs.cpp / unixsock.cpp /
 *  dnsfs.cpp / pipefs.cpp / procfs.cpp)⇒ 不解决它,VFS 就搬不动。
 *
 * ====================================================================
 * 覆盖的规矩(只对**架构相关**的上游头生效)
 * ====================================================================
 *
 * 1. 放在 `arch/arm32/include/upstream/` 下,并**保持上游的相对路径**
 *    (所以是 `upstream/cpu/lock.h`,不是 `upstream/lock.h`);
 * 2. 必须提供与上游**同名、同契约**的东西 —— 不许多也不许少。
 *    这个头之所以能只写一行 include,正是因为 `<arch/cpu.h>` 里那份
 *    `spin_t` 是照上游契约做的(见 `arch/cpu.h:467-506`:它逐条引用了
 *    x86 的 `lock.h:7-10` / `:52` / `:85`,并说明唯一差异是"存 RFLAGS
 *    还是存 CPSR");
 * 3. **实现优先复用移植侧已有的架构层**,不要在覆盖层里再写一份。
 *    重复实现迟早分叉,而分叉的锁是最难查的一类问题。
 *
 * 构建图上靠 `arm32_cxx` 规则的 `-I` 顺序实现:
 *
 *     -I./arch/arm32/include/upstream   ← 覆盖层(最先)
 *     -I./include                       ← 上游头文件树
 *     -I./arch/arm32/include            ← 移植侧自己的头(`<arch/...>`)
 *
 * ⚠ **只有架构相关的头才放覆盖层。** 平台中立的头(如 `fs/vfs/vfs.h`)
 *   要改就直接改上游那一份(见 2026-09-18 的平台中立重构),
 *   不要在这里放一份影子 —— 影子会漂移,而契约测试钉不住它。
 *
 * ====================================================================
 * 与上游的两处已知差异(都是刻意的,不是遗漏)
 * ====================================================================
 *
 * - 上游那个头还 `#include <task/scheduler.h>`。这里没有跟着包含:
 *   那份是 x86 的调度器头,而 ARM 侧用 `<arch/sched.h>`。
 *   谁需要调度器就自己包含自己的 —— "用了什么就包含什么"。
 * - `spin_t` 的字段名是 `locked`/`cpsr`,上游是 `lock`/`rflags`。
 *   这是**架构事实的反映**(见 arch/cpu.h 的说明),不是笔误;
 *   任何"逐字段比对上下游"的检查都不该要求这两个名字相同。
 */

#include <arch/cpu.h>
