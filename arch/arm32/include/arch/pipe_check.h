/*
 * 管道(pipefs)验收判据(M4A-1.5)
 *
 * ====================================================================
 * 验的是什么,以及"为什么没上板就不能算完成"
 * ====================================================================
 *
 * `pipefs.cpp` 从 M4A-1.5 起就在 ARM 图里了(编过、链上),但**它一行都没跑过**。
 * "编过"与"能跑"之间隔着全部语义:环形缓冲的读写、方向标志、
 * `node->size`(= 管道里的字节数,由 `pipefs_stat` 报)、以及**阻塞**那几条路。
 *
 * 所以这里验的是**内存里的一次真实往返**:
 *   建管道 → 写 32 字节 → **管道里确实有 32 字节** → 读回 → 逐字节相同
 *   → **管道里回到 0** → 再验一次"读不会超过管道里的存量"。
 *
 * ★ 其中"管道里有 32 字节"(`arm_pipe_fill`)是**独立观测点**:
 *   `arm_pipe_write()` 返回 32 只说明"它说它写了 32";fill 是管道自己的状态
 *   (`pipefs_stat` 里那句 `node->size = pipe->ptr`)。两者一起才排除
 *   "空壳函数把入参原样返回"这种假通过(坑表 43 的同型)。
 *
 * ====================================================================
 * ⚠⚠ 一条必须遵守的安全约束:不要读**空**管道 ⚠⚠
 * ====================================================================
 *
 * `pipefs_read()`(`pipefs.cpp:74-102`)在没有数据时会
 * **循环 + `pipe_wait_on()` 等写者**,只有在 `write_fds == 0` 时才立即返回 0。
 * 启动自检跑在 kmain 上下文里,读空管道就是**当场挂住**。
 * ⇒ 每一条判据都**先写后读**(下面 `pipe_check_run()` 的顺序就是这个原因,
 *   不是随手排的)。
 */

#include <arch/types.h>

#define PIPE_CHECK_PAYLOAD_LEN 32
/* 短读那一步:写 8 字节、按 32 字节去读,应当只拿到 8 */
#define PIPE_CHECK_SHORT_LEN 8

typedef struct
{
    int setup;       /* `arm_pipefs_setup()`:0 = 挂上了 /pipe */
    int create;      /* `arm_pipe_create()`:0 = 两个节点 + 缓冲都建好了 */
    int write;       /* 写入字节数(期望 = 32)*/
    int fill_after;  /* ★ 写完之后**管道里**的字节数(期望 = 32)*/
    int read;        /* 读回字节数(期望 = 32)*/
    int roundtrip;   /* 1 = 读回内容与写入内容**逐字节相同** */
    int fill_drain;  /* ★ 读完之后管道里的字节数(期望 = 0)*/
    int short_write; /* 短读那一步写入的字节数(期望 = 8)*/
    int short_read;  /* 按 32 字节去读、实际拿到的字节数(期望 = 8)*/
} pipe_check_t;

/* 跑一次起搏 + 验收。**幂等**。⚠ 必须在堆可用且 VFS 起搏之后调 */
const pipe_check_t *pipe_check_run(void);
