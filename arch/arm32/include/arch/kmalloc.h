#pragma once

/*
 * libc 堆接口 —— 把上游那两百多处 malloc/free 接到 ARM 自己的堆上
 *
 * ====================================================================
 * 这个文件解决的是什么问题(合流决策 D2 的落地)
 * ====================================================================
 *
 * M4-1 挑 krlibc 子集时**数过** driver/fs + include/fs + driver/device.cpp:
 * 23 个函数、699 个调用点,其中 malloc/calloc/realloc/free 那一组属于堆,
 * 当时记的是"不算本阶段"(见 krlibc.h 的说明)。M4-3 把堆做出来了,
 * 但两边的**名字**一直没接上 —— ARM 侧只有 heap_alloc(heap_t *, size),
 * 而上游那几百处调用写的是 malloc(size)。
 *
 * 这里就是那一层接线。四个函数都在 <krlibc.h> 里声明,拼写与旧 XJ380 一致,
 * 这样将来上游文件可以直接编进 ARM 图而不必改 include。
 *
 * ====================================================================
 * 为什么不搬上游的 kernel/memory 那一套
 * ====================================================================
 *
 * 合流决策 D2(2026-09-18)定的是"保留 ARM 那份 + 补一层上游形状的接口"。
 * 理由不是偷懒:上游那套 8 个文件 2,196 行里 page.cpp 一个人 871 行,
 * 它拉的是 cpu/longm.h / cpu/regio.h / cpu/fsgsbase.h,而 mm/page.h 又拉
 * <efi/efi.h> —— 那是 x86 4 级页表 + HHDM + UEFI 内存图,等于把计划
 * §2.3 自称"单项风险最高"的工作包重做一遍。
 *
 * 而"对齐接口"这一侧的实测成本很小:那批文件里堆 API 只有
 * **4 个符号、257 处调用**(free 187 / malloc 55 / calloc 10 / realloc 5)
 * —— 就是这个文件。
 *
 * ====================================================================
 * 语义:照 C 标准的那几条,以及这一层自己的责任
 * ====================================================================
 *
 *   malloc(0)        -> 返回**可释放的非 NULL 块**(沿用 ARM 堆的既有语义)
 *   calloc 乘出溢出   -> NULL
 *   realloc(NULL, n) -> 等价 malloc(n)
 *   realloc 失败      -> 原指针**仍然有效**(不释放)
 *   free(NULL)       -> **no-op,不计为错误**(C 标准;上游代码里到处都是)
 *
 * ★ free() 的返回值是 void,而 ARM 的 heap_free() 会**明确告诉你**
 *   指针非法或双重释放(heap.h 的原话:"释放失败必须能被调用方看见")。
 *   接成 void 就等于把这个信号扔了 —— 而"静默失败的 free"正是堆最难查的
 *   一类问题(症状是很久以后的、看起来无关的崩溃)。所以留一个计数出口:
 *   kmalloc_bad_free_count()。调用方与启动冒烟测试都读它。
 *
 * ====================================================================
 * 刻意**没有**提供的两个(别以为它们存在)
 * ====================================================================
 *
 *   aligned_alloc   上游 <mm/alloc/alloc.h> 声明了它,但今天全仓库 0 个调用点。
 *                   真正的对齐分配必须做在**堆内部**(ARM 堆只保证 8 字节);
 *                   在外层多分配再偏移指针是不行的 —— heap_free() 会拒绝
 *                   偏移过的指针,而那条检查正是它抓野指针的手段。
 *                   ⇒ 真需要时(PL 的 DMA 缓冲、VFP 区)是**改堆**,不是加包装。
 *
 *   usable_size     同上,0 个调用点。它要给堆加一个"这块负载多大"的访问器。
 *                   等真有调用方再加,不提前造东西。
 *
 * ====================================================================
 * 下一步(还没做)
 * ====================================================================
 *
 * 上游文件写的是 #include <mm/alloc/alloc.h> / <mm/heap.h>。要让它们直接
 * 编进 ARM 图,还需要一层 include 路径映射(arch/arm32/include/mm/...),
 * 那是 M4A-1.1 的下一步 —— 本文件只负责让**符号**先存在。
 */

#include <arch/heap.h>

/*
 * 绑定内核堆。kmain 在 heap_init() 成功之后调用一次。
 *
 * ⚠ 绑定**之前** malloc/calloc/realloc 一律返回 NULL,而不是崩:
 *   启动早期谁先调到,得到的是"分配失败",不是一次 Data Abort。
 */
void kmalloc_set_heap(heap_t *h);

/*
 * 通过 free() 释放失败的累计次数(非法指针 / 双重释放 / 堆还没绑定)。
 *
 * 这是这一层**唯一**能看见这类错误的地方 —— libc 的 free 没有返回值。
 * 正常应当恒为 0;启动冒烟测试会读它。
 */
u32 kmalloc_bad_free_count(void);
