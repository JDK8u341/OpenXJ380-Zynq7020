#pragma once

/*
 * VFS 起搏 + 验收判据(M4A-1.2b 的验收项)
 *
 * ====================================================================
 * 这一层验的是什么
 * ====================================================================
 *
 * M4A-1.2b 把上游的 VFS 核心(`driver/fs/vfs/vfs.cpp`,1433 行)与
 * `tmpfs`(323 行)**搬进了 ARM 内核**。到 `da645bf` 为止,证据只到
 * "**链接**成功、0 个未定义符号" —— 而链接成功**不等于**它能用:
 * 一个空壳也能链接成功。
 *
 * 所以这里的判据是 M4A-1.2b 计划里写死的那一条:
 *   **建 / 读 / 写 / 列目录**,全部在内存里(tmpfs),不需要块设备。
 *
 * 它按证据强度分三层,和本项目其它地方一致:
 *
 *   1. **往返**:写进去 32 字节、读回来逐字节相同(最强的一层);
 *   2. **挂载真的发生了**:`/tmp` 的 `fsid` 必须**不同于**根目录的 ——
 *      tmpfs 的 `tmpfs_mount()` 里写着 `node->fsid = tmpfs_id`
 *      (`tmpfs.cpp:111`),没挂上就还是根文件系统的普通目录;
 *   3. **反面控制**:在**根**文件系统上做同样的往返必须**失败**。
 *      ⚠ 这一条不是装饰:没有它,"建文件成功"可能是假通过 ——
 *      上游给未挂载节点的回调表填的是 `empty_func`(`vfs.cpp` 里
 *      `static void empty_func() {}`),它的返回值是**未定义的**,
 *      于是"没挂载"很容易表现成"调用成功"。
 *
 * ====================================================================
 * 为什么判据在 C 里、而调用在 C++ 里
 * ====================================================================
 *
 * `include/fs/vfs/vfs.h` **整个文件没有 `extern "C"`** ⇒ VFS 的公开函数
 * 都是 C++ 链接的(`_Z8vfs_initv` 实测)。移植侧的 C 给不出这些符号名,
 * 所以"调用 VFS"必须发生在落地层(`arch/arm32/src/upstream_api.cpp`)。
 * 但落地层只做**转发与安装** —— 什么算通过、阈值多少,全在这里。
 */

#include <arch/types.h>

/*
 * 探针载荷长度。**放在头文件里**是要紧的:自检报告的判据
 * (`vfs_write` / `vfs_read` 必须等于它)要用同一个数 ——
 * 两份各写一个 32,哪天改动一边就会变成"两条判据互相矛盾"的那种假绿。
 *
 * 取 32 的理由:比一个指针宽、比一页小,而且不是 0 的倍数关系,
 * 少读/多读/读错偏移都会让长度或内容对不上。
 */
#define VFS_CHECK_PAYLOAD_LEN 32

/* 探针的原始读数。⚠ 全是**实测值**,不在下面做任何判断(判断在 kmain 的报告项里) */
typedef struct
{
    int bringup;     /* `arm_vfs_bringup()` 的返回:0 = 成功,-1 = vfs_init 失败,-2 = tmpfs 失败 */
    int fsid_root;   /* 根目录节点的 fsid */
    int fsid_tmp;    /* `/tmp` 节点的 fsid —— 必须 != fsid_root,否则挂载没发生 */
    int create_a;    /* 建 `/tmp/xj380_a.txt` 的返回(0 = 成功) */
    int create_b;    /* 建 `/tmp/xj380_b.txt` 的返回 */
    int write_a;     /* 往 a.txt 写入的字节数(期望 = 载荷长度) */
    int read_a;      /* 从 a.txt 读回的字节数 */
    int payload_len; /* 载荷长度(判据要用它,所以记进来而不是散在代码里) */
    int roundtrip;   /* 1 = 读回内容与写入内容**逐字节相同** */
    int list_before; /* 建文件**之前** `/tmp` 的子项数 */
    int list_after;  /* 建文件**之后** `/tmp` 的子项数 */
    int cwd_root;    /* 1 = 内核进程的 cwd 已指向根目录 */
    int neg_create;  /* 反面控制:在**根** fs 上建文件 */
    int neg_write;   /* 反面控制:在根 fs 上写入的字节数 */
    int neg_read;    /* 反面控制:从根 fs 上读回的字节数 */
    int negative_ok; /* 1 = 根 fs 上的往返**没有**成立(证明上一层的成功不是假通过) */
} vfs_check_t;

/*
 * 跑一次起搏 + 验收。**幂等**:第二次调用直接返回上一次的结果表
 * (重复起搏会重新 `vfs_init()`,把根目录换掉)。
 *
 * ⚠ 必须在**堆可用之后**调用(`vfs_init()` 与 `queue_init()` 都要 malloc)。
 */
const vfs_check_t *vfs_check_run(void);
